--  DDL for View VW_REPARTIDOR_TOTAL_AMONESTACIONES
--------------------------------------------------------

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "CLETAEATS"."VW_REPARTIDOR_TOTAL_AMONESTACIONES" ("REPARTIDOR_ID", "TOTAL_AMONESTACIONES") AS 
  SELECT
    r.repartidor_id,
    COUNT(CASE WHEN a.activa = 'S' THEN 1 END) AS total_amonestaciones
FROM repartidor r
LEFT JOIN amonestacion_repartidor a
       ON a.repartidor_id = r.repartidor_id
GROUP BY r.repartidor_id
;
--------------------------------------------------------
--  DDL for View VW_TOTAL_PEDIDOS_POR_CLIENTE
--------------------------------------------------------

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "CLETAEATS"."VW_TOTAL_PEDIDOS_POR_CLIENTE" ("CLIENTE_ID", "CLIENTE", "TOTAL_PEDIDOS") AS 
  SELECT
    c.cliente_id,
    u.nombre_completo AS cliente,
    COUNT(p.pedido_id) AS total_pedidos
FROM cliente c
JOIN usuario u
  ON u.usuario_id = c.usuario_id
LEFT JOIN pedido p
  ON p.cliente_id = c.cliente_id
GROUP BY c.cliente_id, u.nombre_completo
;
