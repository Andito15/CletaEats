--  DDL for View VW_TOTAL_VENDIDO_POR_RESTAURANTE
--------------------------------------------------------

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "CLETAEATS"."VW_TOTAL_VENDIDO_POR_RESTAURANTE" ("RESTAURANTE_ID", "RESTAURANTE", "TOTAL_VENDIDO", "TOTAL_PEDIDOS") AS 
  SELECT
    r.restaurante_id,
    r.nombre AS restaurante,
    NVL(SUM(f.monto_total), 0) AS total_vendido,
    COUNT(DISTINCT p.pedido_id) AS total_pedidos
FROM restaurante r
LEFT JOIN pedido p
       ON p.restaurante_id = r.restaurante_id
LEFT JOIN factura f
       ON f.pedido_id = p.pedido_id
GROUP BY r.restaurante_id, r.nombre
;
